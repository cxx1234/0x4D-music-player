/// 索引字母分桶工具：把排序键（或原文）首字符映射为索引分组标签。
///
/// 分组规则：
/// - 拉丁字母 → 对应大写字母（A-Z）；
/// - 日文假名（平假名/片假名，含浊音/半浊音/拗音/小写假名）→ 五十音行
///   （平假名 10 行：あ か さ た な は ま や ら わ）；
/// - 其余（数字/符号/无法归类）→ '#'。
///
/// 供列表索引滚动条（拖动滑块时显示当前索引字母）使用。
library;

/// 返回 [sortKey]（如 title_sort_key / name_sort_key）首字符对应的索引字母。
///
/// 优先取 [sortKey] 首字符——英文/中文拼音都已被 `buildSortKey` 归一为小写
/// 字母，直接映射为大写；[sortKey] 为空或 null 时回退 [fallback]（原文本），
/// 再兜底 '#'。
String indexLetterFor(String? sortKey, String fallback) {
  final src = (sortKey != null && sortKey.isNotEmpty) ? sortKey : fallback;
  if (src.isEmpty) return '#';
  final code = src.codeUnitAt(0);
  // 拉丁字母 A-Z / a-z → 对应大写字母。
  if ((code >= 0x41 && code <= 0x5A) || (code >= 0x61 && code <= 0x7A)) {
    return src[0].toUpperCase();
  }
  return _kanaRows[src[0]] ?? '#';
}

